import assert from 'node:assert/strict';
import { execFileSync } from 'node:child_process';
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';

const root = mkdtempSync(join(tmpdir(), 'cms-backup-recovery-'));
const blog = join(root, 'blog');
const remote = join(root, 'remote.git');
const peer = join(root, 'peer');
const git = (directory: string, ...args: string[]) => execFileSync('git', ['-C', directory, ...args], { encoding: 'utf8', stdio: 'pipe' }).trim();
execFileSync('git', ['init', '-q', '-b', 'main', blog]);
execFileSync('git', ['init', '-q', '--bare', remote]);
git(blog, 'config', 'user.name', 'CMS Test');
git(blog, 'config', 'user.email', 'cms-test@example.test');
git(blog, 'config', 'commit.gpgsign', 'false');
writeFileSync(join(blog, 'post.md'), 'Keep this post unchanged.\n');
git(blog, 'add', '.');
git(blog, 'commit', '-qm', 'base content');
git(blog, 'remote', 'add', 'origin', remote);
git(blog, 'push', '-qu', 'origin', 'main');
execFileSync('git', ['clone', '-q', '-b', 'main', remote, peer]);
git(peer, 'config', 'user.name', 'CMS Peer');
git(peer, 'config', 'user.email', 'cms-peer@example.test');
git(peer, 'config', 'commit.gpgsign', 'false');
process.env.BLOG_CONTENT_BASE_DIR = blog;
process.env.BLOG_CMS_DB = join(root, 'cms.db');
const { appendRevision, getMetaValue, getStoredPost, setMetaValue } = await import('./db.ts');
const { getBackupStatus, reconcileBackup, replacePendingBackup, runBackup } = await import('./backup.ts');
const rejectPush = () => writeFileSync(join(remote, 'hooks/pre-receive'), '#!/bin/sh\nexit 1\n', { mode: 0o755 });
const allowPush = () => rmSync(join(remote, 'hooks/pre-receive'));
const advanceRemote = () => {
	git(peer, 'pull', '--ff-only', '-q');
	writeFileSync(join(peer, 'remote-only.txt'), `Remote change ${git(peer, 'rev-parse', 'HEAD')}\n`);
	git(peer, 'add', '.');
	git(peer, 'commit', '-qm', 'remote advanced');
	git(peer, 'push', '-q', 'origin', 'main');
};

try {
	appendRevision('post.md', 'title: Post', 'Newer saved CMS text.', 'saved', 'cms');
	const stored = getStoredPost('post.md');
	rejectPush();
	await assert.rejects(runBackup(), /Backup push failed/);
	const original = getBackupStatus().pendingCommit!;
	assert.match(getBackupStatus().error!, /Backup push failed/);
	allowPush();
	advanceRemote();
	git(blog, 'fetch', '-q', 'origin');
	git(blog, 'rebase', 'origin/main');
	git(blog, 'push', '-q', 'origin', 'main');
	const rewritten = git(blog, 'rev-parse', 'HEAD');
	assert.notEqual(rewritten, original);
	writeFileSync(join(blog, 'local-only.txt'), 'Must stay local.\n');
	git(blog, 'add', 'local-only.txt');
	git(blog, 'commit', '-qm', 'unrelated local work');
	const localHead = git(blog, 'rev-parse', 'HEAD');
	await runBackup();
	assert.equal(getBackupStatus().pendingCommit, '');
	assert.equal(git(blog, 'rev-parse', 'HEAD'), localHead);
	assert.equal(git(blog, 'rev-parse', 'origin/main'), rewritten);
	assert.equal(getBackupStatus().error, '');
	git(blog, 'reset', '--hard', 'origin/main');
	rejectPush();
	await assert.rejects(runBackup(), /Backup push failed/);
	const abandoned = getBackupStatus().pendingCommit!;
	allowPush();
	advanceRemote();
	git(blog, 'fetch', '-q', 'origin');
	git(blog, 'reset', '--hard', 'origin/main');
	const before = git(blog, 'rev-parse', 'HEAD');
	await assert.rejects(runBackup(), /HEAD no longer contains the saved backup/);
	assert.match(getBackupStatus().error!, /Verify backup delivery/);
	assert.equal(git(blog, 'rev-parse', 'HEAD'), before);
	const undelivered = await reconcileBackup(abandoned);
	assert.equal(undelivered.ok, false);
	assert.equal(getBackupStatus().remoteCommit, before);
	writeFileSync(join(blog, 'post.md'), 'Unsaved local Git edit.\n');
	await assert.rejects(replacePendingBackup(abandoned, before), /clean main checkout/);
	assert.equal(readFileSync(join(blog, 'post.md'), 'utf8'), 'Unsaved local Git edit.\n');
	git(blog, 'restore', 'post.md');
	writeFileSync(join(blog, '.git/hooks/pre-commit'), '#!/bin/sh\nexit 1\n', { mode: 0o755 });
	const index = readFileSync(join(blog, '.git/index'));
	const priorBackup = readFileSync(join(blog, '.cms/cms-backup.db'));
	await assert.rejects(replacePendingBackup(abandoned, before), /Backup commit failed/);
	assert.deepEqual(readFileSync(join(blog, '.git/index')), index);
	assert.deepEqual(readFileSync(join(blog, '.cms/cms-backup.db')), priorBackup);
	assert.equal(getBackupStatus().pendingCommit, abandoned);
	rmSync(join(blog, '.git/hooks/pre-commit'));
	advanceRemote();
	await assert.rejects(replacePendingBackup(abandoned, before), /Remote main changed/);
	const refreshed = await reconcileBackup(abandoned);
	assert.equal(refreshed.ok, false);
	await assert.rejects(replacePendingBackup(abandoned, refreshed.remoteCommit), /clean main checkout/);
	git(blog, 'reset', '--hard', 'origin/main');
	rejectPush();
	await assert.rejects(replacePendingBackup(abandoned, refreshed.remoteCommit), /Backup push failed/);
	const replacement = getBackupStatus().pendingCommit;
	assert.notEqual(replacement, abandoned);
	assert.equal(getMetaValue('supersededBackupPush'), abandoned);
	assert.equal(git(blog, 'diff', '--name-only', 'origin/main', 'HEAD'), '.cms/cms-backup.db');
	allowPush();
	await runBackup();
	assert.equal(getBackupStatus().pendingCommit, '');
	assert.equal(git(blog, 'rev-parse', 'origin/main'), replacement);
	assert.deepEqual(getStoredPost('post.md'), stored);
	assert.equal(readFileSync(join(blog, 'post.md'), 'utf8'), 'Keep this post unchanged.\n');
	const missing = 'a'.repeat(40);
	setMetaValue('pendingBackupPush', missing);
	await assert.rejects(runBackup(), /HEAD no longer contains the saved backup/);
	const absent = await reconcileBackup(missing);
	assert.equal(absent.ok, false);
	assert.equal((await replacePendingBackup(missing, absent.remoteCommit)).ok, true);
	assert.equal(getBackupStatus().pendingCommit, '');
	await assert.rejects(reconcileBackup(missing), /Saved backup changed/);
	console.log('backup-recovery.check: ok');
} finally {
	rmSync(root, { recursive: true, force: true });
}
