import assert from 'node:assert/strict';
import { execFileSync } from 'node:child_process';
import { existsSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';

const root = mkdtempSync(join(tmpdir(), 'cms-publication-recovery-'));
const blog = join(root, 'blog');
const remote = join(root, 'remote.git');
const peer = join(root, 'peer');
const git = (directory: string, ...args: string[]) => execFileSync('git', ['-C', directory, ...args], { encoding: 'utf8', stdio: 'pipe' }).trim();
execFileSync('git', ['init', '-q', '-b', 'main', blog]);
execFileSync('git', ['init', '-q', '--bare', remote]);
for (const directory of [blog]) {
	git(directory, 'config', 'user.name', 'CMS Test');
	git(directory, 'config', 'user.email', 'cms-test@example.test');
	git(directory, 'config', 'commit.gpgsign', 'false');
}
const original = Array.from({ length: 30 }, (_, index) => `Paragraph ${index}`).join('\n') + '\n';
writeFileSync(join(blog, 'post.md'), original);
git(blog, 'add', 'post.md');
git(blog, 'commit', '-qm', 'base content');
git(blog, 'remote', 'add', 'origin', remote);
git(blog, 'push', '-qu', 'origin', 'main');
execFileSync('git', ['clone', '-q', '-b', 'main', remote, peer]);
git(peer, 'config', 'user.name', 'CMS Peer');
git(peer, 'config', 'user.email', 'cms-peer@example.test');
git(peer, 'config', 'commit.gpgsign', 'false');
process.env.BLOG_CONTENT_BASE_DIR = blog;
process.env.BLOG_CMS_DB = join(root, 'cms.db');
const { appendRevision, getPublishedPosts, getStoredPost, recordPublished, setStaged, getStagedPaths } = await import('./db.ts');
const { setPendingPublishPush, getPendingPublishPush } = await import('./publish-push.ts');
const { getPublicationRecovery, reconcilePublication, readPendingPublicationPatch } = await import('./publish-recovery.ts');

try {
	appendRevision('post.md', 'title: Post', 'Approved text in the store.', 'approved-hash', 'cms');
	setStaged('post.md', true);
	writeFileSync(join(blog, 'post.md'), original.replace('Paragraph 0\n', 'Approved opening\n'));
	git(blog, 'commit', '-qam', 'pending publication');
	const pending = git(blog, 'rev-parse', 'HEAD');
	setPendingPublishPush(pending);
	recordPublished([{ path: 'post.md', title: 'Post', slug: 'post', contentHash: 'approved-hash' }], pending);
	const stored = getStoredPost('post.md');
	const published = getPublishedPosts();
	writeFileSync(join(peer, 'post.md'), original.replace('Paragraph 29\n', 'Independent remote edit\n'));
	git(peer, 'commit', '-qam', 'remote advanced');
	git(peer, 'push', '-q', 'origin', 'main');
	const notDelivered = await reconcilePublication(pending);
	assert.equal(notDelivered.ok, false);
	assert.deepEqual(notDelivered.paths, ['post.md']);
	assert.match(notDelivered.message, /download the captured patch/i);
	assert.equal(getPendingPublishPush(), pending);
	assert.match(await readPendingPublicationPatch(pending), /\+Approved opening/);
	git(blog, 'fetch', '-q', 'origin');
	git(blog, 'rebase', 'origin/main');
	git(blog, 'push', '-q', 'origin', 'main');
	const rewritten = git(blog, 'rev-parse', 'HEAD');
	assert.notEqual(rewritten, pending);
	git(peer, 'pull', '--ff-only', '-q');
	writeFileSync(join(peer, 'unrelated.txt'), 'Unrelated work is not the delivery commit.\n');
	git(peer, 'add', 'unrelated.txt');
	git(peer, 'commit', '-qm', 'work after delivery');
	const notDelivery = git(peer, 'rev-parse', 'HEAD');
	writeFileSync(join(peer, 'post.md'), readFileSync(join(peer, 'post.md'), 'utf8').replace('Approved opening', 'A later remote edit'));
	git(peer, 'commit', '-qam', 'edit after delivery');
	git(peer, 'push', '-q', 'origin', 'main');
	let laterRemote = git(peer, 'rev-parse', 'HEAD');
	const laterTree = git(peer, 'rev-parse', 'HEAD^{tree}');
	for (let followup = 0; followup < 270; followup += 1) {
		laterRemote = git(peer, 'commit-tree', laterTree, '-p', laterRemote, '-m', `remote followup ${followup}`);
	}
	git(peer, 'update-ref', 'refs/heads/main', laterRemote);
	git(peer, 'push', '-q', 'origin', 'main');
	const index = readFileSync(join(blog, '.git/index'));
	const content = readFileSync(join(blog, 'post.md'));
	assert.equal((await reconcilePublication(pending)).ok, false, 'tip-only proof must not undo a later remote edit');
	assert.equal((await reconcilePublication(pending, { commit: pending, remote: laterRemote, confirmed: true })).ok, false,
		'a selected commit outside the remote history cannot prove delivery');
	const coincidentContent = await reconcilePublication(pending, { commit: notDelivery, remote: laterRemote, confirmed: true });
	assert.equal(coincidentContent.ok, false);
	assert.match(coincidentContent.message, /parent already contains/);
	await assert.rejects(reconcilePublication(pending, { commit: rewritten, remote: rewritten, confirmed: true }), /Verify current remote/);
	const delivered = await reconcilePublication(pending, { commit: rewritten, remote: laterRemote, confirmed: true });
	assert.equal(delivered.ok, true);
	assert.equal(delivered.remoteCommit, laterRemote);
	assert.equal(delivered.deliveryCommit, rewritten);
	assert.equal(getPublicationRecovery().lastDelivery.commit, rewritten);
	assert.equal(getPublicationRecovery().lastDelivery.authorConfirmed, true);
	assert.equal(getPublicationRecovery().lastDelivery.capturedCommit, pending);
	assert.deepEqual(getPublishedPosts(), published, 'the captured published snapshot keeps its original commit provenance');
	assert.equal(git(peer, 'show', 'main:post.md').includes('A later remote edit'), true);
	assert.equal(getPendingPublishPush(), '');
	assert.deepEqual(readFileSync(join(blog, '.git/index')), index);
	assert.deepEqual(readFileSync(join(blog, 'post.md')), content);
	assert.equal(git(blog, 'rev-parse', 'HEAD'), rewritten);
	assert.deepEqual(getStoredPost('post.md'), stored);
	assert.ok(getStagedPaths().has('post.md'));
	writeFileSync(join(blog, 'post.md'), content.toString().replace('Approved opening', 'Another queued opening'));
	git(blog, 'commit', '-qam', 'second pending publication');
	const second = git(blog, 'rev-parse', 'HEAD');
	setPendingPublishPush(second);
	git(peer, 'pull', '--ff-only', '-q');
	writeFileSync(join(peer, 'post.md'), content.toString().replace('Approved opening', 'Conflicting remote choice'));
	git(peer, 'commit', '-qam', 'divergent remote');
	git(peer, 'push', '-q', 'origin', 'main');
	const divergent = await reconcilePublication(second);
	assert.equal(divergent.ok, false);
	assert.deepEqual(divergent.paths, ['post.md']);
	assert.equal(getPendingPublishPush(), second);
	assert.deepEqual(getStoredPost('post.md'), stored);
	await assert.rejects(reconcilePublication(pending), /Pending publication changed/);
	git(peer, 'fetch', '-q', blog, second);
	const sideDelivery = git(peer, 'commit-tree', git(peer, 'rev-parse', `${second}^{tree}`), '-p', 'HEAD', '-m', 'publication on a side branch');
	git(peer, 'merge', '--no-ff', '-s', 'ours', sideDelivery, '-m', 'merge without delivering the side branch content');
	git(peer, 'push', '-q', 'origin', 'main');
	const undeliveredMerge = git(peer, 'rev-parse', 'HEAD');
	assert.equal((await reconcilePublication(second)).ok, false);
	const sideBranch = await reconcilePublication(second, { commit: sideDelivery, remote: undeliveredMerge, confirmed: true });
	assert.equal(sideBranch.ok, false, 'a matching side-branch snapshot merged without its content was never delivered on main');
	assert.match(sideBranch.message, /first-parent/);
	writeFileSync(join(blog, 'earlier-queued.txt'), 'Earlier queued content must be exported.\n');
	git(blog, 'add', 'earlier-queued.txt');
	git(blog, 'commit', '-qm', 'earlier queued content');
	writeFileSync(join(blog, 'final-queued.txt'), 'Final queued content must be exported.\n');
	git(blog, 'add', 'final-queued.txt');
	git(blog, 'commit', '-qm', 'final queued content');
	setPendingPublishPush(git(blog, 'rev-parse', 'HEAD'));
	const completePatch = await readPendingPublicationPatch(getPendingPublishPush()!);
	assert.match(completePatch, /\+Earlier queued content/);
	assert.match(completePatch, /\+Final queued content/);
	const queuedTip = getPendingPublishPush()!;
	git(peer, 'fetch', '-q', blog, queuedTip);
	git(peer, 'cherry-pick', queuedTip);
	git(peer, 'push', '-q', 'origin', 'main');
	const partialTip = git(peer, 'rev-parse', 'HEAD');
	assert.equal((await reconcilePublication(queuedTip)).ok, false);
	assert.equal((await reconcilePublication(queuedTip, { commit: partialTip, remote: partialTip, confirmed: true })).ok, false,
		'the selected final patch cannot conceal undelivered earlier queued changes');
	assert.equal(getPendingPublishPush(), queuedTip);
	writeFileSync(join(peer, 'next.txt'), 'Remote advanced after verification.\n');
	git(peer, 'add', 'next.txt');
	git(peer, 'commit', '-qm', 'another remote change');
	git(peer, 'push', '-q', 'origin', 'main');
	await assert.rejects(reconcilePublication(queuedTip, { commit: partialTip, remote: partialTip, confirmed: true }), /Remote main changed/);
	const missing = 'a'.repeat(40);
	setPendingPublishPush(missing);
	const unavailable = await reconcilePublication(missing);
	assert.equal(unavailable.ok, false);
	assert.match(unavailable.message, /restore it from a clone or backup/);
	assert.equal(getPendingPublishPush(), missing);
	await assert.rejects(readPendingPublicationPatch(missing), /Restore any missing Git objects/);
	setPendingPublishPush(queuedTip);
	const mergeDelivery = git(peer, 'commit-tree', git(peer, 'rev-parse', `${queuedTip}^{tree}`),
		'-p', 'HEAD', '-p', sideDelivery, '-m', 'complete delivery through a merge');
	git(peer, 'reset', '--hard', mergeDelivery);
	writeFileSync(join(peer, 'post.md'), 'A newer edit after the merged publication.\n');
	git(peer, 'commit', '-qam', 'later edit after merged delivery');
	git(peer, 'push', '-q', 'origin', 'main');
	const afterMerge = git(peer, 'rev-parse', 'HEAD');
	assert.equal((await reconcilePublication(queuedTip)).ok, false);
	assert.equal((await reconcilePublication(queuedTip, { commit: mergeDelivery, remote: afterMerge, confirmed: true })).ok, true);
	assert.equal(git(peer, 'show', 'HEAD:post.md'), 'A newer edit after the merged publication.');
	assert.deepEqual(getStoredPost('post.md'), stored);
	git(blog, 'fetch', '-q', 'origin');
	git(blog, 'reset', '--hard', 'origin/main');
	writeFileSync(join(blog, 'reverted-publication.md'), 'A publication later removed by a remote revert.\n');
	git(blog, 'add', 'reverted-publication.md');
	git(blog, 'commit', '-qm', 'publication that will be reverted');
	const revertedCapture = git(blog, 'rev-parse', 'HEAD');
	setPendingPublishPush(revertedCapture);
	writeFileSync(join(peer, 'independent.txt'), 'Independent work before the rebase.\n');
	git(peer, 'add', 'independent.txt');
	git(peer, 'commit', '-qm', 'remote advanced before delivery');
	git(peer, 'push', '-q', 'origin', 'main');
	git(blog, 'fetch', '-q', 'origin');
	git(blog, 'rebase', 'origin/main');
	git(blog, 'push', '-q', 'origin', 'main');
	const revertedDelivery = git(blog, 'rev-parse', 'HEAD');
	git(peer, 'pull', '--ff-only', '-q');
	git(peer, 'revert', '--no-edit', revertedDelivery);
	git(peer, 'push', '-q', 'origin', 'main');
	const revertedRemote = git(peer, 'rev-parse', 'HEAD');
	const revertedIndex = readFileSync(join(blog, '.git/index'));
	const preview = await reconcilePublication(revertedCapture);
	assert.equal(preview.ok, false);
	assert.deepEqual(preview.currentRemote?.differences, [
		{ path: 'reverted-publication.md', kind: 'deleted', matchesBefore: true }
	]);
	assert.deepEqual(getPublicationRecovery().currentRemote, preview.currentRemote);
	const revertedResult = await reconcilePublication(revertedCapture, { commit: revertedDelivery, remote: revertedRemote, confirmed: true });
	assert.equal(revertedResult.ok, true);
	assert.match(revertedResult.message, /Historical Git delivery/);
	assert.match(revertedResult.message, /does not verify.*deployment|deployment.*not verified/i);
	assert.deepEqual(revertedResult.currentRemote, preview.currentRemote);
	assert.equal(existsSync(join(peer, 'reverted-publication.md')), false);
	assert.deepEqual(readFileSync(join(blog, '.git/index')), revertedIndex);
	assert.equal(git(blog, 'rev-parse', 'HEAD'), revertedDelivery);
	assert.deepEqual(getStoredPost('post.md'), stored);
	console.log('publish-recovery.check: ok');
} finally {
	rmSync(root, { recursive: true, force: true });
}
